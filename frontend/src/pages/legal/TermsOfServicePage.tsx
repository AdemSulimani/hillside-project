export default function TermsOfServicePage() {
  const contentLines = TERMS_TEXT.split('\n').slice(3);
  const blocks: Array<{ type: 'heading' | 'subheading' | 'paragraph' | 'list'; value: string | string[] }> = [];
  let listBuffer: string[] = [];

  const flushList = () => {
    if (listBuffer.length > 0) {
      blocks.push({ type: 'list', value: listBuffer });
      listBuffer = [];
    }
  };

  for (const line of contentLines) {
    const trimmed = line.trim();

    if (!trimmed) {
      flushList();
      continue;
    }

    const isSectionHeading = /^\d+\.\s/.test(trimmed);
    const isSubsectionHeading = /^\d+\.\d+\s/.test(trimmed);
    const isBulletLine = /^[a-z].*[;.]$/.test(trimmed);

    if (isSectionHeading) {
      flushList();
      blocks.push({ type: 'heading', value: trimmed });
      continue;
    }

    if (isSubsectionHeading) {
      flushList();
      blocks.push({ type: 'subheading', value: trimmed });
      continue;
    }

    if (isBulletLine) {
      listBuffer.push(trimmed);
      continue;
    }

    flushList();
    blocks.push({ type: 'paragraph', value: trimmed });
  }

  flushList();

  return (
    <div className="mx-auto w-full max-w-5xl px-6 py-12">
      <h1 className="text-3xl font-bold tracking-tight">Terms of Service</h1>
      <p className="mt-2 text-sm text-muted-foreground">Effective Date: April 14, 2026</p>
      <p className="text-sm text-muted-foreground">Last Updated: April 21, 2026</p>

      <div className="mt-8 space-y-3 text-sm leading-6 text-foreground">
        {blocks.map((block, index) => {
          if (block.type === 'heading') {
            return <h2 key={index} className="pt-2 text-xl font-semibold">{block.value as string}</h2>;
          }

          if (block.type === 'subheading') {
            return <h3 key={index} className="pt-1 text-base font-semibold">{block.value as string}</h3>;
          }

          if (block.type === 'list') {
            return (
              <ul key={index} className="list-disc space-y-1 pl-5">
                {(block.value as string[]).map((item) => (
                  <li key={item}>{item}</li>
                ))}
              </ul>
            );
          }

          return <p key={index}>{block.value as string}</p>;
        })}
      </div>
    </div>
  );
}
